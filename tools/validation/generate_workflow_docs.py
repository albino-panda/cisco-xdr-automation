#!/usr/bin/env python3
"""Generate the MITRE mapping and the workflow index from workflow definitions and legacy specs.

Usage:
    python tools/validation/generate_workflow_docs.py --check   # exit 1 when a generated file is stale
    python tools/validation/generate_workflow_docs.py --write   # rewrite the generated files

Sources (architecture section 14.5.5):

- migrated workflows: ``discover_workflows()`` from ``xdr_response.workflows.discovery`` (empty until
  the workflow framework and the first migrated workflow exist);
- legacy specs: every ``workflows/<id>/workflow.yaml`` still present (``xdr_plan.repo``), except the
  ones a migrated definition replaces (``id`` or ``legacy_id``).

Outputs, all deterministic and marked "do not edit":

- ``docs/mitre-mapping/mitre-mapping.yaml`` (``schema_version: 2``);
- ``docs/mitre-mapping/README.md``;
- ``docs/workflows/README.md``.

The tool only reads specs and definitions and writes these three files. It never calls an adapter.
Exit codes: 0 up to date (or written), 1 stale files (``--check``), 2 usage error.
"""
from __future__ import annotations

import argparse
import sys
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
for _extra in (REPO_ROOT / "src", REPO_ROOT / "engine"):  # run from a checkout without install
    if _extra.is_dir() and str(_extra) not in sys.path:
        sys.path.insert(0, str(_extra))

GENERATOR = "tools/validation/generate_workflow_docs.py"
MD_HEADER = f"<!-- generated by {GENERATOR}; do not edit -->"
YAML_HEADER = f"# generated by {GENERATOR}; do not edit"
MITRE_YAML = Path("docs/mitre-mapping/mitre-mapping.yaml")
MITRE_README = Path("docs/mitre-mapping/README.md")
WORKFLOWS_README = Path("docs/workflows/README.md")

# Phase of every workflow (architecture 14.5.1); legacy specs carry no phase of their own.
PHASES: Mapping[str, int] = {
    "ransomware": 2, "phishing": 2, "account-takeover": 2, "mail-bombing": 2, "malware": 2, "mfa-fatigue": 2,
    "password-spray": 2, "bec": 2, "malicious-powershell": 3, "credential-dumping": 3, "lateral-movement": 3,
    "persistence": 3, "unauthorized-rmm": 3, "c2": 4, "dns-tunneling": 4, "exfiltration": 4,
    "suspicious-authentication": 4, "cloud-compromise": 4, "privilege-escalation": 5, "threat-intel-sweep": 5,
    "vulnerability-exploitation": 5, "web-attacks": 5,
}

MITRE_NOTES = (
    "Mail bombing maps to T1667 *Email Bombing* (added in ATT&CK v17). The legacy spec mapped it by effect "
    "to T1499 *Endpoint Denial of Service*; that forced mapping was dropped when the workflow migrated.",
    "T1219 was renamed *Remote Access Tools* in ATT&CK v17; the ID is unchanged.",
    "Legacy specs carry no tactic; tactics appear when a workflow migrates to a `WorkflowDefinition` "
    "(every mapping there names its tactic and a rationale, so no mapping is forced).",
)


@dataclass(frozen=True)
class Tactic:
    """An ATT&CK tactic reference."""

    id: str
    name: str


@dataclass(frozen=True)
class TechniqueRef:
    """One ATT&CK technique or sub-technique a workflow responds to."""

    id: str
    name: str
    tactics: tuple[Tactic, ...] = ()


@dataclass(frozen=True)
class WorkflowEntry:
    """What the generated documents need to know about one workflow."""

    id: str
    name: str
    phase: int | None
    status: str  # "migrated" | "legacy spec"
    severity: str
    techniques: tuple[TechniqueRef, ...]
    actions: tuple[str, ...]
    integrations: tuple[str, ...]
    scenarios: int
    handoffs: tuple[str, ...] = ()  # WorkflowDefinition.handoff_to (migrated workflows only)


@dataclass
class _Technique:
    id: str
    name: str
    tactics: dict[str, str] = field(default_factory=dict)
    workflows: set[str] = field(default_factory=set)


# ----------------------------------------------------------------------------- sources


def _value(obj: Any) -> str:
    """String value of an enum member or a plain value."""
    return str(getattr(obj, "value", obj))


def _count(directory: Path) -> int:
    return len(list(directory.glob("*.yaml"))) if directory.is_dir() else 0


def load_catalog(package: str = "xdr_response.workflows") -> list[Any]:
    """Definitions of every migrated workflow; empty while the workflow framework is not built yet."""
    try:
        from xdr_response.workflows.discovery import discover_workflows  # noqa: PLC0415
    except ModuleNotFoundError as exc:
        if exc.name and (exc.name == "xdr_response.workflows" or exc.name.startswith("xdr_response.workflows.")):
            return []
        raise
    catalog = discover_workflows(package)
    return [catalog.get(wid).definition for wid in catalog.ids()]


def migrated_entry(definition: Any, root: Path) -> WorkflowEntry:
    """Turn a ``WorkflowDefinition`` into a ``WorkflowEntry``."""
    techniques: dict[str, TechniqueRef] = {}
    for m in definition.mitre:
        name = m.sub_technique_name or m.technique_name
        tactic = Tactic(m.tactic, m.tactic_name)
        known = techniques.get(m.attack_id)
        tactics = tuple(sorted({*(known.tactics if known else ()), tactic}, key=lambda t: t.id))
        techniques[m.attack_id] = TechniqueRef(m.attack_id, name, tactics)
    actions = tuple(dict.fromkeys(_value(r.action) for r in definition.recommendations))
    return WorkflowEntry(
        id=definition.id,
        name=definition.name,
        phase=int(definition.phase),
        status="migrated",
        severity=_value(definition.default_severity).lower(),
        techniques=tuple(techniques.values()),
        actions=actions,
        integrations=tuple(r.integration for r in definition.required_integrations),
        scenarios=_count(root / "tests" / "fixtures" / "workflows" / definition.id),
        handoffs=tuple(getattr(definition, "handoff_to", ()) or ()),
    )


def legacy_entry(spec: Mapping[str, Any], root: Path) -> WorkflowEntry:
    """Turn a legacy ``workflow.yaml`` into a ``WorkflowEntry`` (no tactics)."""
    wid = str(spec["id"])
    actions: list[str] = []
    for step in spec.get("steps", []):
        if step.get("phase") == "contain" and step.get("atomic") and step["atomic"] not in actions:
            actions.append(step["atomic"])
    return WorkflowEntry(
        id=wid,
        name=str(spec.get("name", wid)),
        phase=PHASES.get(wid),
        status="legacy spec",
        severity=str(spec.get("default_severity", "")).lower(),
        techniques=tuple(TechniqueRef(str(t["id"]), str(t["name"])) for t in spec.get("mitre_attack", [])),
        actions=tuple(actions),
        integrations=tuple(str(i) for i in spec.get("integrations", [])),
        scenarios=_count(root / "workflows" / wid / "scenarios"),
    )


def collect(root: Path, definitions: Iterable[Any], legacy_specs: Iterable[Mapping[str, Any]]) -> list[WorkflowEntry]:
    """Migrated workflows first claim their ids and legacy ids; remaining legacy specs fill the rest."""
    entries = {d.id: migrated_entry(d, root) for d in definitions}
    replaced = set(entries) | {d.legacy_id for d in definitions if getattr(d, "legacy_id", None)}
    for spec in legacy_specs:
        if spec["id"] not in replaced:
            entries[str(spec["id"])] = legacy_entry(spec, root)
    return [entries[k] for k in sorted(entries)]


def load_legacy_specs() -> list[dict]:
    """Every remaining legacy spec, via ``xdr_plan.repo``."""
    from xdr_plan import repo  # noqa: PLC0415

    return [repo.load_workflow(wid) for wid in repo.workflow_ids()]


# ----------------------------------------------------------------------------- rendering


def _technique_key(tid: str) -> tuple[int, int]:
    base, _, sub = tid[1:].partition(".")
    return int(base), int(sub or 0)


def techniques(entries: Sequence[WorkflowEntry]) -> list[_Technique]:
    """Techniques sorted by ATT&CK id; the first name seen (migrated entries first) wins."""
    ordered = sorted(entries, key=lambda e: (e.status != "migrated", e.id))
    found: dict[str, _Technique] = {}
    for entry in ordered:
        for ref in entry.techniques:
            tech = found.setdefault(ref.id, _Technique(ref.id, ref.name))
            tech.tactics.update({t.id: t.name for t in ref.tactics})
            tech.workflows.add(entry.id)
    return [found[k] for k in sorted(found, key=_technique_key)]


def render_mitre_yaml(entries: Sequence[WorkflowEntry]) -> str:
    """``docs/mitre-mapping/mitre-mapping.yaml`` (schema_version 2)."""
    data = {
        "schema_version": 2,
        "techniques": [
            {
                "id": t.id,
                "name": t.name,
                "tactics": [{"id": k, "name": t.tactics[k]} for k in sorted(t.tactics)],
                "workflows": sorted(t.workflows),
            }
            for t in techniques(entries)
        ],
    }
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, default_flow_style=False, width=100)
    return f"{YAML_HEADER}\n{body}"


def _attack_url(tid: str) -> str:
    return "https://attack.mitre.org/techniques/" + tid.replace(".", "/") + "/"


def _workflow_link(wid: str, prefix: str) -> str:
    return f"[`{wid}`]({prefix}workflows/{wid}/README.md)"


def render_mitre_readme(entries: Sequence[WorkflowEntry]) -> str:
    """``docs/mitre-mapping/README.md``."""
    lines = [
        MD_HEADER,
        "# MITRE ATT&CK mapping",
        "",
        "Which workflow handles each technique. Generated from the `mitre` field of every migrated "
        "`WorkflowDefinition` and the `mitre_attack` field of every remaining legacy `workflow.yaml`; "
        "the same data is in [`mitre-mapping.yaml`](mitre-mapping.yaml) for import into coverage tools "
        "such as ATT&CK Navigator. Regenerate with "
        f"`python {GENERATOR} --write`.",
        "",
        "| Technique | Name | Tactics | Workflows |",
        "|---|---|---|---|",
    ]
    for t in techniques(entries):
        tactics = ", ".join(f"{k} {t.tactics[k]}" for k in sorted(t.tactics)) or "-"
        flows = ", ".join(_workflow_link(w, "../../") for w in sorted(t.workflows))
        lines.append(f"| [{t.id}]({_attack_url(t.id)}) | {t.name} | {tactics} | {flows} |")
    lines += ["", "## Notes", ""] + [f"- {note}" for note in MITRE_NOTES]
    return "\n".join(lines) + "\n"


def render_workflows_readme(entries: Sequence[WorkflowEntry]) -> str:
    """``docs/workflows/README.md``: index of every workflow, migrated or legacy."""
    lines = [
        MD_HEADER,
        "# Workflows",
        "",
        "Index of every workflow. `migrated` workflows are `WorkflowDefinition`s in "
        "`src/xdr_response/workflows/`; `legacy spec` workflows are still `workflows/<id>/workflow.yaml` "
        "specs checked by `xdr_plan`. Every action listed is only a recommendation: it needs a human "
        "approval (ELEVATED for critical assets and over blast-radius caps) before the lifecycle "
        f"executes it. \"Hands off to\" lists the workflows a run may suggest next (a note for the analyst; "
        f"nothing is started). Regenerate with `python {GENERATOR} --write`.",
        "",
        "| Workflow | Phase | Status | Severity | ATT&CK | Recommended actions | Required integrations | Scenarios "
        "| Hands off to |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        attack = ", ".join(t.id for t in e.techniques) or "-"
        actions = ", ".join(f"`{a}`" for a in e.actions) or "-"
        integrations = ", ".join(f"`{i}`" for i in e.integrations) or "-"
        phase = str(e.phase) if e.phase is not None else "-"
        handoffs = ", ".join(f"`{h}`" for h in e.handoffs) or "-"
        lines.append(f"| {_workflow_link(e.id, '../../')} | {phase} | {e.status} | {e.severity} | "
                     f"{attack} | {actions} | {integrations} | {e.scenarios} | {handoffs} |")
    return "\n".join(lines) + "\n"


def render_all(entries: Sequence[WorkflowEntry]) -> dict[Path, str]:
    """Every generated file, relative to the repository root."""
    return {
        MITRE_YAML: render_mitre_yaml(entries),
        MITRE_README: render_mitre_readme(entries),
        WORKFLOWS_README: render_workflows_readme(entries),
    }


# ----------------------------------------------------------------------------- check / write


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8").replace("\r\n", "\n")
    except FileNotFoundError:
        return None


def stale_files(root: Path, files: Mapping[Path, str]) -> list[str]:
    """One problem line per generated file that is missing or differs."""
    problems = []
    for rel, content in files.items():
        current = _read(root / rel)
        if current is None:
            problems.append(f"{rel.as_posix()}: missing; run python {GENERATOR} --write")
        elif current != content:
            problems.append(f"{rel.as_posix()}: out of date; run python {GENERATOR} --write")
    return problems


def write_files(root: Path, files: Mapping[Path, str]) -> list[Path]:
    """Write the files that differ; return the paths written."""
    written = []
    for rel, content in files.items():
        if _read(root / rel) == content:
            continue
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(content, encoding="utf-8", newline="\n")
        written.append(rel)
    return written


def build(root: Path = REPO_ROOT) -> dict[Path, str]:
    """Collect every source and render every generated file."""
    return render_all(collect(root, load_catalog(), load_legacy_specs()))


def check(root: Path = REPO_ROOT) -> list[str]:
    """Problems of ``--check``; empty when every generated file is up to date."""
    return stale_files(root, build(root))


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="generate_workflow_docs", description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="rewrite the generated files")
    mode.add_argument("--check", action="store_true", help="exit 1 when a generated file is stale")
    args = parser.parse_args(argv)
    files = build(REPO_ROOT)
    if args.check:
        problems = stale_files(REPO_ROOT, files)
        for line in problems:
            print(line)
        return 1 if problems else 0
    for rel in write_files(REPO_ROOT, files):
        print(f"wrote {rel.as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
